#!/usr/bin/env bash
# Generates docs/protocol/schema.json from docs/protocol/proto.ts, and from it the Swift source
# that embeds the tool inputSchemas in sirius-mcp. Node is needed here only, never at run time.
# Commit both outputs. `--check` fails if either is out of date.
set -euo pipefail

GENERATOR="ts-json-schema-generator@2.9.0"
TYPES=(DisplayParams NotifyParams SpeakParams)

root="$(cd "$(dirname "$0")/.." && pwd)"
source_ts="$root/docs/protocol/proto.ts"
out_json="$root/docs/protocol/schema.json"
out_swift="$root/Sources/sirius-mcp/Schemas.swift"

check=false
[[ "${1:-}" == "--check" ]] && check=true

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# Each Params type inlined into one self-contained object schema, so hosts have no $ref to resolve.
#   --jsDoc none             proto.ts's comments carry review status, not
#                            guidance for a model; the tool descriptions say what matters.
#   --additional-properties  unknown fields are ignored at every level (proto.ts, Envelope),
#                            so the schema must not forbid them.
for type in "${TYPES[@]}"; do
  npx -y "$GENERATOR" --path "$source_ts" --type "$type" \
    --expose none --no-top-ref --jsDoc none --additional-properties \
    > "$work/$type.json"
done

jq -n --arg generator "$GENERATOR" \
  --slurpfile display "$work/DisplayParams.json" \
  --slurpfile notify "$work/NotifyParams.json" \
  --slurpfile speak "$work/SpeakParams.json" '
  def clean: del(.["$schema"], .definitions);
  {
    "$schema": "http://json-schema.org/draft-07/schema#",
    "$comment": "Generated from docs/protocol/proto.ts by scripts/gen-schema.sh (\($generator)). Do not edit.",
    definitions: {
      DisplayParams: ($display[0] | clean),
      NotifyParams: ($notify[0] | clean),
      SpeakParams: ($speak[0] | clean)
    }
  }' > "$work/schema.json"

{
  echo "// Generated by scripts/gen-schema.sh from docs/protocol/schema.json. Do not edit."
  echo "// Embedded so the binary never reads a file at run time."
  echo ""
  echo "enum Schemas {"
  for type in "${TYPES[@]}"; do
    name="$(tr '[:upper:]' '[:lower:]' <<<"${type:0:1}")${type:1}"
    json="$(jq -c --arg t "$type" '.definitions[$t]' "$work/schema.json")"
    # A raw string ends at "#; compact JSON from jq never contains it, but fail loudly if it does.
    if [[ "$json" == *'"#'* ]]; then
      echo "gen-schema: $type contains \"#, which would end the raw string" >&2
      exit 1
    fi
    printf '    static let %s = #"%s"#\n' "$name" "$json"
  done
  echo "}"
} > "$work/Schemas.swift"

if $check; then
  status=0
  cmp -s "$work/schema.json" "$out_json" || { echo "gen-schema: ${out_json#"$root"/} is out of date" >&2; status=1; }
  cmp -s "$work/Schemas.swift" "$out_swift" || { echo "gen-schema: ${out_swift#"$root"/} is out of date" >&2; status=1; }
  exit $status
fi

cp "$work/schema.json" "$out_json"
cp "$work/Schemas.swift" "$out_swift"
echo "wrote ${out_json#"$root"/} and ${out_swift#"$root"/}"
